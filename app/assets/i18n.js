/* ---------- current language (English by default) ---------- */
const LANG_KEY = 'aragontask.lang';
let LANG = 'en';
try {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === 'zh' || saved === 'en') LANG = saved;
} catch (e) { /* storage unavailable */ }

/* ---------- translate: t(key, ...args) ---------- */
function t(key) {
  const d = I18N[LANG] || I18N.en;
  const has = (o, k) => Object.prototype.hasOwnProperty.call(o, k);
  let s = has(d, key) ? d[key] : (has(I18N.en, key) ? I18N.en[key] : key);
  const args = Array.prototype.slice.call(arguments, 1);
  if (args.length && typeof args[0] === 'number' && args[0] === 1 && has(d, key + '_one')) {
    s = d[key + '_one'];
  }
  s = String(s);
  for (let i = 0; i < args.length; i++) {
    s = s.split('{' + i + '}').join(args[i] == null ? '' : String(args[i]));
  }
  return s;
}

/* ---------- apply to static markup (data-i18n / -ph / -al) ---------- */
function applyI18n() {
  document.documentElement.lang = LANG === 'zh' ? 'zh-CN' : 'en';
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.placeholder = t(el.getAttribute('data-i18n-ph'));
  });
  document.querySelectorAll('[data-i18n-al]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-al')));
  });
}

/* ---------- switch language (persist + re-apply static text) ---------- */
function setLang(l) {
  LANG = (l === 'zh') ? 'zh' : 'en';
  try { localStorage.setItem(LANG_KEY, LANG); } catch (e) { /* ignore */ }
  applyI18n();
}

/* initial pass — this script loads at the end of <body>, before first paint */
applyI18n();
